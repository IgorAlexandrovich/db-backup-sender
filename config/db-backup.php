<?php

/*
|--------------------------------------------------------------------------
| Конфигурация резервного копирования базы данных
|--------------------------------------------------------------------------
|
| Публикуется командой:
|     php artisan vendor:publish --tag=db-backup-config
|
| Все значения можно переопределить в .env. Секретные значения (токен) не
| должны попадать в репозиторий: храните их только в .env.
|
*/

return [

    /*
    |--------------------------------------------------------------------------
    | Включение резервного копирования
    |--------------------------------------------------------------------------
    |
    | Полный «выключатель»: при false команда backup:run завершается успешно,
    | но ничего не делает. Удобно для локальной разработки и стендов.
    |
    */
    'enabled' => env('BACKUP_ENABLED', true),

    /*
    |--------------------------------------------------------------------------
    | Имя проекта
    |--------------------------------------------------------------------------
    |
    | Должно совпадать с именем проекта в config.json приёмника: именно по
    | этому имени создаётся отдельная папка на сервере резервных копий.
    | Разрешены буквы, цифры, точка, дефис и подчёркивание.
    |
    */
    'project' => env('BACKUP_PROJECT_NAME', env('APP_NAME', 'laravel')),

    /*
    |--------------------------------------------------------------------------
    | Удалённый приёмник
    |--------------------------------------------------------------------------
    |
    | url    — полный адрес /api/upload приёмника (только HTTPS);
    | token  — секретный токен проекта (выдаётся при установке приёмника);
    | header — имя HTTP-заголовка с токеном (должно совпадать с приёмником).
    |
    | allow_insecure_http разрешает http:// вместо https://. Нужен только для
    | локальных проверок: по умолчанию передача данных без TLS запрещена.
    |
    */
    'remote' => [
        'url' => env('BACKUP_REMOTE_URL'),
        'token' => env('BACKUP_TOKEN'),
        'header' => env('BACKUP_HEADER_NAME', 'X-Backup-Token'),
        'timeout' => (int) env('BACKUP_TIMEOUT', 180),
        'verify_ssl' => (bool) env('BACKUP_VERIFY_SSL', true),
        'allow_insecure_http' => (bool) env('BACKUP_ALLOW_INSECURE_HTTP', false),
    ],

    /*
    |--------------------------------------------------------------------------
    | Повторные попытки отправки
    |--------------------------------------------------------------------------
    |
    | retries     — сколько всего попыток отправки (1 = без повторов);
    | retry_delay — пауза между попытками в секундах.
    |
    | Повторяются только временные ошибки: сетевые сбои, таймауты, ответы
    | 5xx, 408 и 429. Ошибки авторизации и несовпадение контрольной суммы
    | не повторяются — это ошибки конфигурации, повтор их не исправит.
    |
    */
    'retries' => max(1, (int) env('BACKUP_RETRIES', 3)),
    'retry_delay' => max(0, (int) env('BACKUP_RETRY_DELAY', 5)),

    /*
    |--------------------------------------------------------------------------
    | Утилита mysqldump
    |--------------------------------------------------------------------------
    |
    | binary — путь к mysqldump. Пустое значение означает поиск в PATH.
    | timeout_seconds — максимальное время дампа (0 = без ограничения).
    |
    | extra_arguments — дополнительные аргументы mysqldump. Примеры:
    |   '--set-gtid-purged=OFF'  (MySQL 8 с GTID)
    |   '--column-statistics=0'  (клиент MySQL 8 против сервера 5.7)
    |   '--skip-routines'        (если нет прав на процедуры)
    |
    | ВНИМАНИЕ: --single-transaction даёт согласованный снимок только для
    | таблиц InnoDB. Для таблиц MyISAM снимок не согласован (см. backup:check).
    |
    */
    'mysqldump' => [
        'binary' => env('BACKUP_MYSQLDUMP_PATH', ''),
        'timeout_seconds' => (int) env('BACKUP_DUMP_TIMEOUT', 0),
        'extra_arguments' => [
            // '--set-gtid-purged=OFF',
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | Подключение к базе данных
    |--------------------------------------------------------------------------
    |
    | connection — имя подключения из config/database.php (null = default).
    | check_engines — предупреждать о таблицах не на InnoDB: для них
    |                 --single-transaction не даёт согласованного снимка.
    |
    */
    'connection' => env('BACKUP_DB_CONNECTION'),

    'check_engines' => (bool) env('BACKUP_CHECK_ENGINES', true),

    /*
    |--------------------------------------------------------------------------
    | Сжатие
    |--------------------------------------------------------------------------
    |
    | level — уровень gzip (1..9). 6 — разумный компромисс скорость/размер.
    |
    */
    'compression' => [
        'level' => min(9, max(1, (int) env('BACKUP_GZIP_LEVEL', 6))),
    ],

    /*
    |--------------------------------------------------------------------------
    | Временные файлы
    |--------------------------------------------------------------------------
    |
    | temp_path — каталог для промежуточных дампов (относительно base_path,
    | если путь относительный).
    |
    | ВАЖНО: при ошибке временные файлы НЕ удаляются — дамп нельзя удалять
    | до подтверждённой отправки, иначе разбираться в причине будет нечем.
    | После успешной отправки временные файлы удаляются всегда (кроме запуска
    | с флагом --keep-temp). Очистка старых каталогов выполняется вручную.
    |
    */
    'temp_path' => env('BACKUP_TEMP_PATH', 'storage/app/backups'),

    /*
    |--------------------------------------------------------------------------
    | Уведомления на email
    |--------------------------------------------------------------------------
    |
    | Отправляются только при ошибках (включая недоступность приёмника).
    | from — адрес отправителя; null означает использовать config('mail.from').
    |
    */
    'email' => [
        'enabled' => (bool) env('BACKUP_EMAIL_ENABLED', true),
        'to' => env('BACKUP_EMAIL'),
        'from' => env('BACKUP_EMAIL_FROM'),
    ],

    /*
    |--------------------------------------------------------------------------
    | Планировщик
    |--------------------------------------------------------------------------
    |
    | Пакет сам регистрирует задачу в Laravel Scheduler. enabled=false
    | отключает автоматическую регистрацию (например, если вы запускаете
    | backup:run из собственного cron или другого расписания).
    |
    | cron — выражение cron; по умолчанию каждый час.
    | without_overlapping_minutes — сколько минут держится блокировка от
    | параллельных запусков (защита от «наслоения» тяжёлых дампов).
    |
    */
    'schedule' => [
        'enabled' => (bool) env('BACKUP_SCHEDULE_ENABLED', true),
        'cron' => env('BACKUP_SCHEDULE_CRON', '0 * * * *'),
        'without_overlapping_minutes' => (int) env('BACKUP_SCHEDULE_LOCK_MINUTES', 90),
    ],

    /*
    |--------------------------------------------------------------------------
    | Логирование
    |--------------------------------------------------------------------------
    |
    | Отдельный канал, чтобы события резервного копирования не терялись в
    | общем логе приложения. Если канал с именем channel уже объявлен в
    | config/logging.php, используется он.
    |
    */
    'logging' => [
        'channel' => env('BACKUP_LOG_CHANNEL', 'db-backup'),
        'driver' => env('BACKUP_LOG_DRIVER', 'daily'),
        'path' => env('BACKUP_LOG_PATH', storage_path('logs/db-backup.log')),
        'level' => env('BACKUP_LOG_LEVEL', 'debug'),
        'days' => (int) env('BACKUP_LOG_DAYS', 14),
    ],

];
